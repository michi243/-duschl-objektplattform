'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const legacyMarketing=read('marketing.html');
const legacyPreview=read('preview/v3.41/index.html');
const activeMarketing=read('docs/marketing.html');
const index=read('index.html');
const manifest=JSON.parse(read('release.json'));
const readme=read('README.md');
assert.equal(manifest.version,'3.57.20','release manifest');
assert.match(index,/let APP_VERSION='3\.57\.20'/,'fallback version');
assert.match(index,/let APP_RELEASE_DATE='26\.10\.2026'/,'fallback release date');
assert.match(index,/\.\/docs\/marketing\.html\?v=/,'active marketing navigation');
assert.match(legacyMarketing,/http-equiv="refresh"/);
assert.match(legacyMarketing,/\.\/docs\/marketing\.html/);
assert.match(legacyMarketing,/location\.replace\(new URL\(/);
assert.match(legacyPreview,/http-equiv="refresh"/);
assert.match(legacyPreview,/\.\.\/\.\.\/index\.html/);
assert.match(legacyPreview,/location\.replace\(target\.href\)/);
assert.ok(Buffer.byteLength(legacyMarketing)<2000,'legacy marketing is a small redirect, not a duplicate application');
assert.ok(Buffer.byteLength(legacyPreview)<2000,'old preview code no longer deployed');
assert.ok(activeMarketing.includes('marketing_campaigns'),'active marketing application retained');
assert.match(readme,/v3\.57\.20/);
assert.equal(new URL('./docs/marketing.html','https://example.test/project/marketing.html').pathname,'/project/docs/marketing.html');
assert.equal(new URL('../../index.html','https://example.test/project/preview/v3.41/index.html').pathname,'/project/index.html');
console.log('Repository cleanup, redirects and version gate passed');
