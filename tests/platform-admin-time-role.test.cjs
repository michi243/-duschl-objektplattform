'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const src=fs.readFileSync(require.resolve('../employee-time.js'),'utf8');
new vm.Script(src,{filename:'employee-time.js'});
const match=src.match(/const roleTime=\(\)=>\{([\s\S]*?)\n\};/);
assert.ok(match,'roleTime definition');
const check=new Function('eligibleTimeRole','isPlatformOperatorRole','effectiveOrganizationRole','state','org','uid','return ('+match[0].replace(/^const roleTime=/,'').replace(/;$/,'')+')();');
const perm={permission:{key:'org:staff',enabled:true}};
assert.equal(check(()=>true,()=>true,()=>'staff',perm,()=>'org',()=>'staff'),false,'platform admin never clocks in');
assert.equal(check(()=>true,()=>false,()=>'tenant_admin',perm,()=>'org',()=>'staff'),false,'tenant admin never clocks in');
assert.equal(check(()=>true,()=>false,()=>'employee',perm,()=>'org',()=>'staff'),true,'approved employee can clock in');
assert.equal(check(()=>true,()=>false,()=>'employee',{permission:{key:'org:staff',enabled:false}},()=>'org',()=>'staff'),false,'employee needs approval');
assert.equal(check(()=>true,()=>false,()=>'employee',perm,()=>'other',()=>'staff'),false,'permission cannot cross tenants');
assert.match(src,/id="dstPersonalTimeGrid"/);
assert.match(src,/adminOnly\?\x27none\x27:\x27\x27/);
assert.match(src,/Release manifest v3\.57\.16/);
console.log('Role separation checks passed');
